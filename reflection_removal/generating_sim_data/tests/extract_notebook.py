"""Extracts the reference cells of data_clean.ipynb into importable modules.

Produces nb_ref.py (simulation + culling) and nb_raw.py (RAW reading) next to
this file. That is the reference test_equivalence.py compares the package
against: if you edit the notebook, re-run this script.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NB = HERE.parent.parent / "main_files" / "data_clean.ipynb"

# notebook cells, in the order in which they must be executed
CELLS_SIM = [27, 30, 41, 42, 45, 47, 50, 51, 52, 53, 55, 57, 58, 59, 61, 62]
CELLS_RAW = [8, 16, 19, 21]

HEAD = """# generated by extract_notebook.py -- do not edit
import sys
sys.path.insert(0, {main!r})
import numpy as np, cv2, random, rawpy, exifread
from pathlib import Path
PATCH, TAU, SEED = 384, 0.1329, 1009
"""


def main(nb_path=NB):
    nb_path = Path(nb_path)
    if not nb_path.exists():
        sys.exit(f"notebook not found: {nb_path}")
    cells = [''.join(c['source']) for c in json.loads(nb_path.read_text())['cells']]
    head = HEAD.format(main=str(nb_path.parent))
    for name, keep in (("nb_ref.py", CELLS_SIM), ("nb_raw.py", CELLS_RAW)):
        body = "\n\n".join(f"# ===== CELL {i}\n{cells[i]}" for i in keep)
        (HERE / name).write_text(head + body)
        print(f"{HERE / name} ({len(keep)} cells)")


if __name__ == "__main__":
    main(*sys.argv[1:])
